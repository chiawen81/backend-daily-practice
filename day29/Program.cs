var productPrices = new Dictionary<int, int>
{
    { 101, 30000 },
    { 102, 1200 },
    { 103, 2500 },
    { 104, 8000 }
};





// ==========================================================================================
//                                            主程式
// ==========================================================================================
PrintProductPrices(productPrices);

void PrintProductPrices(
    Dictionary<int, int> collection)
{
    foreach (var item in collection)
    {
        var productTypeText = (item.Value > 5000) ? "高價商品" : "一般商品";
        Console.WriteLine($"ProductId:{item.Key}, Price:{item.Value}, {productTypeText}");
    }
}





